@pytest.mark.asyncio
async def test_distinct_risks_in_same_category_are_both_retained():
    """
    Verifies that two distinct risk findings sharing the same category
    (e.g., Uncapped Indemnity and Limitation of Liability under 'Legal Liability')
    are both retained in merged_findings.
    """
    contract_text = (
        "Section 14.3. Customer shall defend, indemnify, and hold harmless Provider without limitation.\n"
        "Section 15.1. In no event shall Provider be liable for any indirect or consequential damages."
    )
    pages = [PageContent(page_number=1, text=contract_text)]

    distinct_risks = [
        {
            "title": "One-Sided Consequential Damages Waiver",
            "severity": "medium",
            "category": "Legal Liability",
            "clause_reference": "Section 15.1",
            "explanation": "Provider disclaims all indirect damages without reciprocal customer protection.",
            "evidence_snippet": "In no event shall Provider be liable for any indirect or consequential damages.",
            "recommendation": "Make consequential damages waiver mutual."
        }
    ]
    mock_prov = MockLLMProvider(custom_risks=distinct_risks)
    findings, _ = await detect_document_risks_hybrid(pages, "msa_test.docx", provider=mock_prov)

    # Must retain BOTH the rule-based indemnity finding and the LLM damages waiver finding
    legal_liability_findings = [f for f in findings if f.category.lower() == "legal liability"]
    assert len(legal_liability_findings) == 2, (
        f"Expected 2 findings under 'Legal Liability', found {len(legal_liability_findings)}: "
        f"{[f.title for f in legal_liability_findings]}"
    )
    assert any("indemn" in f.title.lower() for f in legal_liability_findings)
    assert any("consequential damages" in f.title.lower() for f in legal_liability_findings)


